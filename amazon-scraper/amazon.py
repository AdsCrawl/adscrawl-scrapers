CLIENT = ScraperClient()

BASE_CONFIG = {


    'countryCode': "US",
}


def _add_or_replace_url_parameters(url: str, **params):
    """adds url parameters or replaces them with new values"""
    parsed_url = urlparse(url)
    query_params = dict(parse_qsl(parsed_url.query))
    query_params.update(params)
    updated_url = parsed_url._replace(query=urlencode(query_params))
    return urlunparse(updated_url)


class ProductPreview(TypedDict):
    """result generated by search scraper"""

    url: str
    title: str
    price: str
    real_price: str
    rating: str
    rating_count: str


def parse_search(result: Response) -> List[ProductPreview]:
    """Parse search result page for product previews"""
    previews = []
    product_boxes = result.selector.css("div.s-result-item[data-component-type=s-search-result]")
    for box in product_boxes:
        url = urljoin(result.url, box.css("div>a::attr(href)").get()).split("?")[0]
        if "/slredirect/" in url:  # skip ads etc.
            continue
        rating = box.xpath("//div[@data-cy='reviews-block']//a[contains(@aria-label, 'out of')]/@aria-label").re_first(r"(\d+\.*\d*) out")
        rating_count = box.xpath("//div[@data-cy='reviews-block']//a[contains(@aria-label, 'ratings')]/@aria-label").get()
        previews.append(
            {
                "url": url,
                "title": box.css("div>a>h2::attr(aria-label)").get(),
                # big price text is discounted price
                "price": box.css(".a-price[data-a-size=xl] .a-offscreen::text").get(),
                # the struck-through list price next to it is the "real" price
                "real_price": box.css(".a-price.a-text-price .a-offscreen::text").get(),
                "rating": float(rating) if rating else None,
                "rating_count": int(rating_count.replace(',','').replace(" ratings", "")) if rating_count else None,
            }
        )
    log.info(f"parsed {len(previews)} product previews from search page {result.url}")
    return previews


@managed
async def scrape_search(url: str, max_pages: Optional[int] = None) -> List[ProductPreview]:
    """Scrape amazon search pages product previews"""
    log.info(f"{url}: scraping first page")

    # Later pages stay on the first page's session. A cold browser for page 2
    # was HTTP 503 on the 2026-11-03 tip2 retest after the one retry.
    session = uuid4().hex
    try:
        first_result = await _fetch_search_page(url, session)
        results = parse_search(first_result)
        _paging_meta = first_result.selector.xpath("//*[@cel_widget_id='UPPER-RESULT_INFO_BAR-0']//span/text()").get()
        _total_results = int(re.findall(r"(?:over\s+)?([\d,]+)\s+results", _paging_meta)[0].replace(',', ''))
        _results_per_page = int(re.findall(r"\d+-(\d+)", _paging_meta)[0])
        total_pages = math.ceil(_total_results / _results_per_page)
        if max_pages and total_pages > max_pages:
            total_pages = max_pages
        log.info(f"{url}: found total results: {_total_results}, scraping {total_pages} pages")
        referer = str(first_result.url)
        for page in range(2, total_pages + 1):
            page_url = _next_search_page(first_result) or _add_or_replace_url_parameters(referer, page=page)
            try:
                result = await _fetch_search_page(page_url, session, referer=referer)
            except ScrapeError as error:
                if not _transient_failure(error):
                    raise
                log.warning(f"search page {page} still failed ({error.code}); one fresh session")
                await CLIENT.close_session(session)
                session = uuid4().hex
                result = await _fetch_search_page(page_url, session, referer=referer)
            results.extend(parse_search(result))
            first_result = result
            referer = str(result.url)
    finally:
        await CLIENT.close_session(session)

    log.info(f"{url}: found total of {len(results)} product previews")
    return results


def _next_search_page(result: Response) -> Optional[str]:
    href = result.selector.css(
        "a.s-pagination-next::attr(href), a[aria-label='Go to next page']::attr(href)"
    ).get()
    if not href:
        return None
    return urljoin("https://www.amazon.com/", href)


async def _fetch_search_page(url: str, session: str, referer: Optional[str] = None) -> Response:
    headers = {"Referer": referer} if referer else {}
    return await _fetch_once_retry(Request(url, **BASE_CONFIG, session=session, headers=headers))

class Review(TypedDict):
    title: str
    text: str
    location_and_date: str
    verified: bool
    rating: float


def _review_title(box) -> str:
    spans = box.css("[data-hook=review-title] span::text, [data-hook=reviewTitle] span::text").getall()
    titles = [span.strip() for span in spans if span.strip() and "out of" not in span]
    if titles:
        return titles[-1]
    raw = box.css("[data-hook=review-title]::text, [data-hook=reviewTitle]::text").get()
    return (raw or "").strip()


def parse_reviews(result: Response) -> List[Review]:
    """parse review from a product page or the /product-reviews/ page.

    Current cards use data-hook review-title and review-body. Older cards use
    reviewTitle and reviewRichContentContainer. Both are accepted.
    """
    review_boxes = result.selector.css("[data-hook=review]")
    parsed = []
    for box in review_boxes:
        rating = box.css("[data-hook*=review-star-rating] ::text").re_first(r"(\d+\.*\d*) out")
        if not rating:
            continue
        text = "".join(
            box.css("[data-hook=review-body] ::text, [data-hook=reviewRichContentContainer] ::text").getall()
        ).strip()
        parsed.append(
            {
                "text": text,
                "title": _review_title(box),
                "location_and_date": (box.css("span[data-hook=review-date] ::text").get() or "").strip(),
                "verified": bool(box.css("span[data-hook=avp-badge] ::text").get()),
                "rating": float(rating),
            }
        )
    return parsed


def _asin_from_url(url: str) -> str:
    match = re.search(r"/(?:dp|gp/product|product-reviews)/([A-Z0-9]{10})", url, re.I)
    return match.group(1) if match else url.rstrip("/").split("/")[-1].split("?")[0]


def reviews_page_url(url: str) -> str:
    """the dedicated reviews document. Product pages often never render the review cards."""
    if "/product-reviews/" in url:
        return url.split("?")[0]
    return f"https://www.amazon.com/product-reviews/{_asin_from_url(url)}/"


def product_page_url(url: str) -> str:
    return f"https://www.amazon.com/dp/{_asin_from_url(url)}"


def next_review_page(result: Response) -> Optional[str]:
    href = result.selector.css(".a-pagination .a-last a::attr(href)").get()
    if not href:
        return None
    return urljoin("https://www.amazon.com/", href)


_TRANSIENT_CODES = {
    "ERR_TUNNEL_CONNECTION_FAILED",
    "ERR_CONNECTION_CLOSED",
    "ERR_HTTP2_PROTOCOL_ERROR",
    "TIMEOUT",
}


def _transient_failure(error: ScrapeError) -> bool:
    if error.code in _TRANSIENT_CODES:
        return True
    status = error.response.status_code if error.response else 0
    return error.code == "HTTP_ERROR" and status in {502, 503}


async def _fetch_once_retry(request: Request) -> Response:
    """one extra attempt for a tunnel drop or a 503, matching the site's existing retry style"""
    try:
        return await CLIENT.fetch(request)
    except ScrapeError as error:
        if not _transient_failure(error):
            raise
        log.warning(f"retrying {request.url} once after {error.code}")
        return await CLIENT.fetch(request)


REVIEWS_AJAX = "https://www.amazon.com/hz/reviews-render/ajax/reviews/get/ref=cm_cr_arp_d_viewopt_srt"


def reviews_ajax_request(asin: str, page: int, referer: str) -> Request:
    """the XHR the product page uses. /product-reviews/ is HTTP 404 for some live ASINs."""
    return Request(
        REVIEWS_AJAX,
        method="POST",
        data={
            "sortBy": "recent",
            "reviewerType": "all_reviews",
            "formatType": "",
            "mediaType": "",
            "filterByStar": "",
            "filterByAge": "",
            "filterByLanguage": "",
            "filterByKeyword": "",
            "shouldAppend": "undefined",
            "deviceType": "desktop",
            "canShowIntHeader": "undefined",
            "pageSize": "20",
            "asin": asin,
            "pageNumber": str(page),
            "scope": f"reviewsAjax{page}",
        },
        headers={
            "content-type": "application/x-www-form-urlencoded;charset=UTF-8",
            "accept": "text/html,*/*",
            "x-requested-with": "XMLHttpRequest",
            "referer": referer,
            "origin": "https://www.amazon.com",
        },
        render=False,
        countryCode="US",
        timeoutMs=60000,
    )


def parse_review_fragments(content: str) -> List[Review]:
    """reviews ajax answers are `&&&` separated JSON chunks whose strings hold the cards"""
    pieces = []
    for chunk in re.split(r"\s*&&&\s*", content or ""):
        chunk = chunk.strip()
        if not chunk:
            continue
        try:
            payload = json.loads(chunk)
        except json.JSONDecodeError:
            if "data-hook" in chunk:
                pieces.append(chunk)
            continue
        if isinstance(payload, list):
            pieces.extend(str(item) for item in payload if isinstance(item, str) and "data-hook" in item)
        elif isinstance(payload, str) and "data-hook" in payload:
            pieces.append(payload)
    if not pieces and content and 'data-hook="review"' in content:
        pieces.append(content)
    reviews: List[Review] = []
    seen = set()
    for html in pieces:
        for review in parse_reviews(Response(REVIEWS_AJAX, html)):
            key = (review["title"], review["text"], review["location_and_date"])
            if key in seen:
                continue
            seen.add(key)
            reviews.append(review)
    return reviews


def _review_request(page_url: str) -> Request:
    return Request(
        page_url,
        render=True,
        autoScroll=True,
        actions=[
            {"type": "waitForSelector", "selector": "[data-hook=review]", "timeoutMs": 12000, "optional": True},
        ],
        **BASE_CONFIG,
    )


def _extend_reviews(reviews: List[Review], seen: set, parsed: List[Review]) -> None:
    for review in parsed:
        key = (review["title"], review["text"], review["location_and_date"])
        if key in seen:
            continue
        seen.add(key)
        reviews.append(review)


@managed
async def scrape_reviews(url: str, max_pages: int = 2) -> List[Review]:
    """scrape product reviews of a given Amazon product URL.

    The reviews ajax endpoint is what the product page calls. /product-reviews/
    returned HTTP 404 for B0BCNKKZ91 and B0CL61F39H, and the product page's
    review widget stayed gated across six renders.
    """
    asin = _asin_from_url(url)
    referer = product_page_url(url)
    log.info(f"scraping reviews for {asin} via the reviews ajax endpoint")
    reviews: List[Review] = []
    seen = set()
    for page_number in range(1, max_pages + 1):
        try:
            page = await _fetch_once_retry(reviews_ajax_request(asin, page_number, referer))
        except ScrapeError as error:
            log.warning(f"reviews ajax page {page_number} failed ({error.code})")
            break
        parsed = parse_review_fragments(page.content)
        if not parsed:
            log.warning(f"reviews ajax page {page_number} had no review cards")
            break
        _extend_reviews(reviews, seen, parsed)
    if reviews:
        log.info(f"scraped {len(reviews)} reviews")
        return reviews

    for page_url in (reviews_page_url(url), referer):
        log.info(f"scraping review page: {page_url}")
        try:
            page = await CLIENT.fetch(_review_request(page_url))
        except ScrapeError as error:
            status = error.response.status_code if error.response else 0
            log.warning(f"{page_url} failed ({error.code} HTTP {status})")
            continue
        parsed = parse_reviews(page)
        if not parsed:
            log.warning(f"review widget was not rendered on {page_url}")
            continue
        _extend_reviews(reviews, seen, parsed)
        page_url = next_review_page(page)
        if page_url and max_pages > 1:
            try:
                nxt = await CLIENT.fetch(_review_request(page_url))
            except ScrapeError as error:
                log.warning(f"next review page failed ({error.code})")
            else:
                _extend_reviews(reviews, seen, parse_reviews(nxt))
        break
    log.info(f"scraped {len(reviews)} reviews")
    return reviews


class Product(TypedDict):
    """type hint storage of Amazons product information"""
    name: str
    asin: str
    style: str
    description: str
    stars: str
    rating_count: str
    features: List[str]
    images: List[str]
    info_table: Dict[str, str]


IMAGE_PATTERNS = [
    r"'colorImages':\s*\{\s*'initial':\s*A\.\$\.parseJSON\('(\[.+?\])'\)",
    r"'imageGalleryData'\s*:\s*A\.\$\.parseJSON\('(\[.+?\])'\)",
    r"'colorImages':\s*\{\s*'initial':\s*(\[.+?\])\s*\}",
    r"'imageGalleryData'\s*:\s*(\[.+?\])\s*,",
]


def parse_images(html: str) -> List[str]:
    """parse product image URLs from the javascript state data embedded in the page HTML"""
    for pattern in IMAGE_PATTERNS:
        if not (match := re.search(pattern, html)):
            continue

        # the payload is a javascript single quoted string, so escaped quotes have to be unescaped
        try:
            data = json.loads(match.group(1).replace("\\'", "'"))
        except json.JSONDecodeError:
            continue

        # every location uses its own key for the full sized image
        images = [img.get("hiRes") or img.get("large") or img.get("mainUrl") for img in data]
        if any(images):
            return [img for img in images if img]
    log.warning("could not find product images in the page state data")
    return []


_STYLE_LABELS = {"style", "color", "colour", "size", "configuration", "pattern", "edition", "format"}


def parse_style(result: Response, asin: str = "") -> Optional[str]:
    """selected variant label. Empty when this ASIN has no style dimension.

    The inline-twister span is empty on the PS5 slim and the 2024 MacBook.
    The dimension JSON and the product-overview row still name the variant.
    """
    sel = result.selector
    parts = []
    css_bits = [
        "[id^=inline-twister-expanded-dimension-text] ::text",
        "#variation_style_name .selection ::text",
        "#variation_color_name .selection ::text",
        "#variation_size_name .selection ::text",
        "#variation_configuration .selection ::text",
        "span[id*=style_name_] ::text",
    ]
    for css in css_bits:
        text = " ".join(piece.strip() for piece in sel.css(css).getall() if piece.strip())
        if text:
            parts.append(text)
    for row in sel.css("#productOverview_feature_div tr, #poExpander tr"):
        cells = [" ".join(cell.css("::text").getall()).strip() for cell in row.css("td, th")]
        cells = [cell for cell in cells if cell]
        if len(cells) < 2:
            continue
        label = cells[0].rstrip(":").lower()
        if label in _STYLE_LABELS and cells[-1] not in parts:
            parts.append(cells[-1])
    match = re.search(r'"dimensionValuesDisplayData"\s*:\s*', result.content or "")
    if match:
        try:
            data, _ = json.JSONDecoder().raw_decode(result.content, match.end())
        except json.JSONDecodeError:
            data = None
        values = data.get(asin) if isinstance(data, dict) else None
        if isinstance(values, list):
            shown = [str(value).strip() for value in values if str(value).strip()]
            if shown:
                parts.append(" / ".join(shown))
    unique = []
    for part in parts:
        if part not in unique:
            unique.append(part)
    return " | ".join(unique) or None


def parse_product(result) -> Product:
    """parse Amazon's product page (e.g. https://www.amazon.com/dp/B07KR2N2GF) for essential product data"""
    images = parse_images(result.content)

    # the other fields can be extracted with simple css selectors
    # we can define our helper functions to keep our code clean
    sel = result.selector
    asin = sel.css("input[name=ASIN]::attr(value)").get("").strip()
    parsed = {
        "name": sel.css("#productTitle::text").get("").strip(),
        "asin": asin,
        # null, not "", when Amazon omits the dimension. The live presence
        # check treats "" as missing and null as an explicit empty variant.
        "style": parse_style(result, asin),
        "description": '\n'.join(sel.css("#productDescription p span ::text").getall()).strip(),
        "stars": sel.css("i[data-hook=average-star-rating] ::text").get("").strip(),
        "rating_count": sel.css("span[data-hook=total-review-count] ::text").get("").strip(),
        "features": [value.strip() for value in sel.css("#feature-bullets li ::text").getall()],
        "images": images,
    }
    # extract details from "Product Information" table:
    info_table = {}
    for row in sel.css('table.prodDetTable tr'):
        label = row.css("th::text").get("").strip()
        value = " ".join(v.strip() for v in row.css("td ::text").getall() if v.strip())
        if label:
            info_table[label] = value
    info_table['Customer Reviews'] = sel.xpath("//div[@id='averageCustomerReviews']//span[@class='a-icon-alt']/text()").get()
    rank = sel.xpath("//tr[th[text()=' Best Sellers Rank ']]//td//text()").getall()
    info_table['Best Sellers Rank'] = ' '.join([text.strip() for text in rank if text.strip()])
    parsed['info_table'] = info_table
    return parsed


NOTICE_TEXT = "Continued access by an unauthorized AI agent"


def _page_summary(result: Response) -> str:
    """describe the page amazon returned instead of the product: its notice page, or the page title and heading"""
    if NOTICE_TEXT in result.content:
        return 'its "unauthorized AI agent" notice page'
    title = result.selector.css("title::text").get("").strip()
    heading = result.selector.css("h1::text, h4::text").get("").strip()
    return f"a page without product data ({title!r} {heading!r})"


@managed
async def scrape_product(url: str) -> List[Product]:
    """scrape Amazon.com product"""
    url = url.split("/ref=")[0]
    asin = url.split("/dp/")[-1]
    log.info(f"scraping product {url}")
    try:
        product_result = await _fetch_once_retry(
            Request(
                url,
                **BASE_CONFIG,
                render=True,
                waitForSelector="#productTitle",
                timeoutMs=120000,
                actions=[{
                    "type": "waitForSelector",
                    "selector": "#productOverview_feature_div, [id^=inline-twister-expanded-dimension-text], #variation_color_name",
                    "timeoutMs": 8000,
                    "optional": True,
                }],
            )
        )
    except ScrapeError as e:
        # amazon sometimes answers with a short page without product data (e.g. a notice) instead of the product
        if e.code != "SELECTOR_NOT_FOUND" or not e.response:
            raise
        raise ValueError(
            f"amazon.com returned {_page_summary(e.response)} instead of the product page {url}"
        ) from e
    variants = [parse_product(product_result)]

    # if product has variants - we want to scrape all of them
    _variation_data = re.findall(r'dimensionValuesDisplayData"\s*:\s*({.+?}),\n', product_result.content)
    if _variation_data:
        variant_asins = [variant_asin for variant_asin in json.loads(_variation_data[0]) if variant_asin != asin]
        # a multipack can list dozens of ASINs. two is enough to prove the variant
        # path; fetching every one stacked timeouts on the 2026-11-03 US retest.
        if len(variant_asins) > 2:
            log.info(f"limiting variants from {len(variant_asins)} to 2")
            variant_asins = variant_asins[:2]
        log.info(f"scraping {len(variant_asins)} variants: {variant_asins}")
        for variant_asin in variant_asins:
            variant_url = f"https://www.amazon.com/dp/{variant_asin}"
            try:
                result = await _fetch_once_retry(Request(variant_url, **BASE_CONFIG, timeoutMs=120000))
            except ScrapeError as error:
                log.warning(f"skipping variant {variant_url}: {error}")
                continue
            # skip variant pages that came back as the notice page (or any page without product data)
            if not result.selector.css("#productTitle"):
                log.warning(f"skipping variant {result.url}: amazon.com returned {_page_summary(result)}")
                continue
            variants.append(parse_product(result))
    return variants
